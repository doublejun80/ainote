let changed = 0;
const keys = Object.keys(additions);
for (const relativePath of keys) {
  const filePath = path.join(repoRoot, relativePath);
  const addition = additions[relativePath];
  const original = fs.readFileSync(filePath, "utf8").replace(/^\uFEFF/, "");
  const match = original.match(/^(---\r?\n[\s\S]*?\r?\n---\r?\n?)([\s\S]*)$/);
  const head = match ? match[1] : "";
  const body = match ? match[2] : original;

  if (body.includes(`## ${addition.heading}`)) {
    continue;
  }

  let summaryIndex = -1;
  for (const marker of ["\n\n정리하면,", "\n\n결국,", "\n\n요약하면,", "\n\n한 문장으로"]) {
    summaryIndex = Math.max(summaryIndex, body.lastIndexOf(marker));
  }

  const block = `\n\n## ${addition.heading}\n\n${addition.body}`;
  const nextBody = summaryIndex >= 0
    ? `${body.slice(0, summaryIndex).trimEnd()}${block}${body.slice(summaryIndex)}`
    : `${body.trimEnd()}${block}\n`;
  const next = `${head}${nextBody.replace(/\n{3,}/g, "\n\n").trimEnd()}\n`;

  if (next !== original) {
    fs.writeFileSync(filePath, next, "utf8");
    changed += 1;
  }
}

console.log(`Enriched ${changed} sections out of ${keys.length}.`);
