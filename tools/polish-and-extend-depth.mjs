for (const dir of fs.readdirSync('manuscript')) {
  const match = dir.match(/^ch(\d{2})$/);
  if (!match) continue;
  const chapter = Number(match[1]);
  for (const file of fs.readdirSync(path.join('manuscript', dir))) {
    if (!/^section-\d{2}\.md$/.test(file)) continue;
    const full = path.join('manuscript', dir, file);
    let text = fs.readFileSync(full, 'utf8').replace(/^\uFEFF/, '');
    text = text.replace(/상황를 생각해 보겠습니다\./g, '상황을 떠올려 보겠습니다.');
    text = text.replace(/흔합니다 이런 오해는/g, '흔합니다. 이런 오해는');
    if (!text.includes('## 이 개념이 책 전체에서 다시 나오는 자리')) {
      text = `${text.trimEnd()}\n\n## 이 개념이 책 전체에서 다시 나오는 자리\n\n${bridge[chapter]}\n`;
    }
    fs.writeFileSync(full, `${text.trimEnd()}\n`, 'utf8');
  }
}
