function renderTail(chapterKey, title, variant) {
  const p = chapterProfiles[chapterKey];
  const lines = [];
  lines.push('');
  lines.push(practicalHeadings[variant]);
  lines.push('');
  lines.push(practicalOpeners[variant](title, p, variant));
  lines.push('');
  lines.push(practicalClosers[variant](title, p, variant));
  lines.push('');
  lines.push(confusionHeadings[variant]);
  lines.push('');
  lines.push(confusionOpeners[variant](title, p));
  lines.push('');
  lines.push(confusionClosers[variant](title, p));
  lines.push('');
  lines.push(practiceHeadings[variant]);
  lines.push('');
  lines.push(practiceOpeners[variant](title));
  lines.push('');
  lines.push('1. ' + p.steps[0](title));
  lines.push('2. ' + p.steps[1](title));
  lines.push('3. ' + p.steps[2](title));
  lines.push('');
  lines.push(connectionHeadings[variant]);
  lines.push('');
  lines.push(connectionOpeners[variant](title, p));
  lines.push('');
  lines.push(connectionClosers[variant](title));
  lines.push('');
  return lines.join('\n');
}

function polishSections() {
  const manuscriptDir = path.join(root, 'manuscript');
  const chapters = fs.readdirSync(manuscriptDir).filter((name) => /^ch\d{2}$/.test(name)).sort();
  const oldMarker = '\n## 실제 개발에서는 이런 판단으로 이어집니다';

  for (const chapter of chapters) {
    const dir = path.join(manuscriptDir, chapter);
    const files = fs.readdirSync(dir).filter((name) => /^section-\d{2}\.md$/.test(name)).sort();
    files.forEach((file, index) => {
      const full = path.join(dir, file);
      const text = fs.readFileSync(full, 'utf8').replace(/^\uFEFF/, '');
      const titleMatch = text.match(/title:\s*"([^"]+)"/);
      const title = titleMatch ? titleMatch[1] : file;
      let next = text;
      const markerIndex = text.indexOf(oldMarker);
      if (markerIndex !== -1) {
        next = text.slice(0, markerIndex) + renderTail(chapter, title, index % 4);
      }
      fs.writeFileSync(full, next.replace(/\n/g, '\r\n'), 'utf8');
    });
  }
}

