let changed = 0;
for (const [relativePath, addition] of Object.entries(additions)) {
  const filePath = path.join(repoRoot, relativePath);
  const original = fs.readFileSync(filePath, "utf8").replace(/^\uFEFF/, "");
  const match = original.match(/^(---\r?\n[\s\S]*?\r?\n---\r?\n?)([\s\S]*)$/);
  const head = match ? match[1] : "";
  const body = match ? match[2] : original;
  if (body.includes(`## ${addition.heading}`)) {
    continue;
  }
  const block = `\n\n## ${addition.heading}\n\n${addition.body}`;
  const next = `${head}${`${body.trimEnd()}${block}`.replace(/\n{3,}/g, "\n\n").trimEnd()}\n`;
  if (next !== original) {
    fs.writeFileSync(filePath, next, "utf8");
    changed += 1;
  }
}

console.log(`Enriched ${changed} chapter/appendix files.`);
